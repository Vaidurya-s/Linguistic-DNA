"""Controlled vocabularies shared by the ORM models, importers and API."""

import enum


class ReuseStatus(enum.StrEnum):
    """Licence decision for a source (Dataset plan §6)."""

    approved = "approved"
    attribution_required = "attribution_required"
    permission_required = "permission_required"
    unknown = "unknown"
    excluded = "excluded"


class ReconstructionStatus(enum.StrEnum):
    attested = "attested"
    reconstructed = "reconstructed"
    uncertain = "uncertain"
    unknown = "unknown"


class NativeFormOrigin(enum.StrEnum):
    """Whether a native-script spelling comes from a source or was generated by us."""

    source = "source"
    derived_transliteration = "derived_transliteration"


class Direction(enum.StrEnum):
    directed = "directed"
    undirected = "undirected"
    unknown = "unknown"


class RelationshipStatus(enum.StrEnum):
    documented = "documented"
    disputed = "disputed"
    candidate = "candidate"
    rejected = "rejected"
    unknown = "unknown"


class SourceConfidence(enum.StrEnum):
    high = "high"
    medium = "medium"
    low = "low"


class RelationshipNamespace(enum.StrEnum):
    lexical = "lexical"
    semantic = "semantic"
    similarity = "similarity"
    classification = "classification"


class FormKind(enum.StrEnum):
    """What kind of unit a form is; only ``word`` can be an exact search match."""

    word = "word"
    stem = "stem"  # trailing hyphen, e.g. māla-
    affix = "affix"  # leading hyphen, e.g. -ṭa-
    root = "root"  # √añc
    compound = "compound"  # documented as having components
    phrase = "phrase"  # contains whitespace


class AuditDecision(enum.StrEnum):
    approved = "APPROVED"
    approved_with_conditions = "APPROVED WITH CONDITIONS"
    # Usable for academic research in the research database and hosted app, with a citation
    # on every record; never redistributed in the public seed.
    research_use = "RESEARCH USE"
    blocked = "BLOCKED"
